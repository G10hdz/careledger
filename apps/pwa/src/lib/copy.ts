const DICT: Record<Lang, Record<CopyKey, string>> = { es, nah, en }

export function translate(lang: Lang, key: CopyKey, vars?: Record<string, string | number>): string {
  let text = DICT[lang][key]
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value))
  }
  return text
}

export function allCopy(): Record<Lang, Record<CopyKey, string>> {
  return DICT
}
